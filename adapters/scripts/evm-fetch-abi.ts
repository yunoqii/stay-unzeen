/**
 * Regenerates src/evm/pons/abi/*.generated.ts from Sourcify (read-only HTTP GET).
 *   pnpm evm:abi
 *
 * Only contracts with a Sourcify match on chain 4663 are fetched. The curve and
 * the launch token are deployed per launch (CREATE2) and are not verified on
 * their own: their ABI is written by hand in abi/curve.ts / abi/token.ts from the
 * verified sources bundled with the factory, and test/evm/pons-abi.test.ts
 * checks every selector against live bytecode.
 */
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const CHAIN = 4663;
const CONTRACTS = [
  { name: "PonsV2LaunchFactory", constName: "ponsV2LaunchFactoryAbi", file: "factory", address: "0x7ed598bcef8bd9edd8c97a195c6d13f40801ec7e" },
  { name: "PonsV2LaunchAndBuy", constName: "ponsV2LaunchAndBuyAbi", file: "launch-and-buy", address: "0xe33e9e479df8802cb0866d5d05258bec4cf62948" },
  { name: "PonsV2FeeEscrow", constName: "ponsV2FeeEscrowAbi", file: "fee-escrow", address: "0xd3afeb2a57f70ef218aa82451c51b2fb0416ac9e" },
] as const;

const OUT = path.resolve(__dirname, "../src/evm/pons/abi");

interface SourcifyContract {
  match: string | null;
  address: string;
  verifiedAt?: string;
  matchId?: string;
  abi?: unknown[];
  compilation?: { name?: string; compilerVersion?: string };
  deployment?: { transactionHash?: string; blockNumber?: string };
}

async function main(): Promise<void> {
  fs.mkdirSync(OUT, { recursive: true });
  for (const c of CONTRACTS) {
    const url = `https://sourcify.dev/server/v2/contract/${CHAIN}/${c.address}?fields=abi,compilation,deployment`;
    const res = await fetch(url);
    if (!res.ok) throw new Error(`${c.name}: Sourcify HTTP ${res.status}`);
    const j = (await res.json()) as SourcifyContract;
    if (!j.match || !Array.isArray(j.abi)) throw new Error(`${c.name}: no verified ABI on Sourcify`);
    if (j.compilation?.name !== c.name) throw new Error(`${c.name}: Sourcify says ${j.compilation?.name}`);
    const abiJson = JSON.stringify(j.abi, null, 2);
    const sha = crypto.createHash("sha256").update(JSON.stringify(j.abi)).digest("hex");
    const body = `// GENERATED by scripts/evm-fetch-abi.ts (pnpm evm:abi). Do not edit.
// Source: Sourcify, ${url.split("?")[0]}
// Contract: ${c.name} @ ${j.address} (chain ${CHAIN}), match: ${j.match}, verifiedAt: ${j.verifiedAt ?? "?"}
// Compiler: ${j.compilation?.compilerVersion ?? "?"}; deployed in tx ${j.deployment?.transactionHash ?? "?"} (block ${j.deployment?.blockNumber ?? "?"})
// sha256(JSON abi): ${sha}
export const ${c.constName} = ${abiJson} as const;
`;
    fs.writeFileSync(path.join(OUT, `${c.file}.generated.ts`), body);
    console.log(`${c.name}: ${j.abi.length} entries, sha256 ${sha.slice(0, 16)}…`);
  }
}

main().catch((e) => {
  console.error(e instanceof Error ? e.message : String(e));
  process.exit(1);
});
