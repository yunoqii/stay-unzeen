//! Creator fees (API.md v0.7, RELAYER.md v4): the relayer's global sweeper records landed
//! sweeps in `creator_fee_sweeps`; core credits `kind = 'creator'` rows to the creator's anon key
//! (`creator_tokens`) as claimable lamports, on an epoch boundary (never at the moment a sweep
//! lands). `partner` rows and mints without an Unzeen creator are pool revenue. `claim` is a
//! ledger-only operation: claimable lamports → ZEC balance at the sell rate (v0.14: plus the
//! zat owed for ZEC-pair fees, 1:1).
//!
//! Privacy (D1): `credited_at` is hour-coarse, claimable rows carry day-coarse times, the
//! journal lives 48 h, claim amounts are scrubbed with the action after 24–48 h.
//!
//! Launch-tx fee (API v0.9, owner decision 12.10): the creator fee generated by the launch tx
//! itself (the creator's initial buy of `create`, every participant's buy of a fair launch)
//! belongs to the pool. Settlement records it in `creator_tokens.launch_fee_lamports`
//! ([`launch_creator_fee`]); crediting withholds it from the first sweeps of the mint.

use deadpool_postgres::GenericClient;
use serde_json::json;

use crate::{
    ActionReceipt, CreatorRules, Ledger, LedgerError, Result,
    actions::{NewAction, RateUsed, ZAT_PER_ZEC},
    journal,
    num::Num,
    to_i64, to_u64,
};

/// Creator fee of a confirmed launch tx (lamports): the relayer's exact figure when it reported
/// one (`relayer_jobs.out_creator_fee`), otherwise an upper bound `ceil(out_lamports × bps /
/// 10 000)` of the venue (pump.fun creator fee is 0.05–0.30 % of the curve leg by fee tier;
/// DBC: 1 % fee × 80 % after Meteora × 50 % creator = 0.40 % of the input). Never more than
/// what the tx paid. Erring high only keeps the participants' money with the pool.
pub fn launch_creator_fee(rules: &CreatorRules, venue: Option<&str>, out_lamports: i128, fact: Option<i128>) -> i128 {
    let paid = out_lamports.max(0);
    if let Some(f) = fact {
        return f.clamp(0, paid);
    }
    let bps = match venue {
        Some("meteora-dbc") => rules.launch_fee_bps_dbc,
        _ => rules.launch_fee_bps_pumpfun,
    } as u128;
    // paid ≤ i128::MAX and bps ≤ u32::MAX: the product can exceed u128 only for absurd inputs.
    let fee = (paid as u128).saturating_mul(bps).div_ceil(10_000);
    fee.min(paid as u128) as i128
}

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct CreditReport {
    /// Sweeps credited (fully or partly) to a creator.
    pub credited: u64,
    /// Sweeps kept whole by the pool (partner side, mint without an Unzeen creator, or fully
    /// withheld as the launch-tx fee).
    pub pool_revenue: u64,
    /// Lamports withheld from creator sweeps as the launch-tx fee (pool's).
    pub withheld_lamports: u128,
}

impl Ledger {
    /// Credit every confirmed, uncredited creator sweep of `network` (one transaction).
    ///
    /// v0.14 (RELAYER v9): a ZEC SPL sweep (`quote_mint` = ZEC SPL) is owed 1:1 in zat
    /// (`creator_claimable.zat`, launch fee withheld from `launch_fee_zat_left`); a USDC/USD1
    /// sweep is credited by its `lamports` (pool-A equivalent from the sweeper) like a SOL one,
    /// and waits uncredited while that equivalent is missing.
    pub async fn credit_fee_sweeps(&self, network: &str) -> Result<CreditReport> {
        let mut c = self.pool.get().await?;
        let tx = c.transaction().await?;
        let zec = crate::rebalance::ZEC_SPL_MINT;
        let rows = tx
            .query(
                "SELECT s.id, s.mint, s.lamports, ct.anon_pubkey, s.quote_mint = $2,
                        CASE WHEN s.quote_amount <= 9223372036854775807 THEN s.quote_amount END
                 FROM creator_fee_sweeps s LEFT JOIN creator_tokens ct ON ct.mint = s.mint
                 WHERE s.network = $1 AND s.status = 'confirmed' AND s.kind = 'creator' AND s.credited_at IS NULL
                   AND (s.quote_mint IS NULL OR s.quote_mint = $2
                        OR COALESCE(s.lamports, 0) > 0 OR COALESCE(s.quote_amount, 0) = 0)
                 FOR UPDATE OF s SKIP LOCKED",
                &[&network, &zec],
            )
            .await?;
        let mut rep = CreditReport::default();
        for r in &rows {
            // Lamport (wei) side is NUMERIC(78,0); the ZEC side is zat (BIGINT columns), so a ZEC
            // SPL sweep above i64::MAX units is not a real sweep: left to the operator.
            let (id, mint, lamports, pk): (i64, String, Option<Num>, Option<Vec<u8>>) =
                (r.get(0), r.get(1), r.get(2), r.get(3));
            let is_zec = r.get::<_, Option<bool>>(4).unwrap_or(false);
            if is_zec && r.get::<_, Option<Num>>(5).is_none() {
                continue;
            }
            let amount: i128 = if is_zec { r.get::<_, Option<Num>>(5) } else { lamports }
                .unwrap_or_default()
                .0
                .max(0);
            let (left_col, claim_col) = if is_zec {
                ("launch_fee_zat_left", "zat")
            } else {
                ("launch_fee_left", "lamports")
            };
            let pool_part: i128 = match pk {
                Some(pk) if amount > 0 => {
                    // Launch-tx fee first: the pool's share comes out of the earliest sweeps.
                    let left: i128 = tx
                        .query_one(
                            &format!("SELECT {left_col} FROM creator_tokens WHERE mint = $1 FOR UPDATE"),
                            &[&mint],
                        )
                        .await?
                        .get::<_, Num>(0)
                        .0;
                    let pool_part = left.clamp(0, amount);
                    if pool_part > 0 {
                        tx.execute(
                            &format!("UPDATE creator_tokens SET {left_col} = {left_col} - $2 WHERE mint = $1"),
                            &[&mint, &Num(pool_part)],
                        )
                        .await?;
                        if !is_zec {
                            rep.withheld_lamports += pool_part as u128;
                        }
                    }
                    let to_creator = amount - pool_part;
                    if to_creator > 0 {
                        tx.execute(
                            &format!(
                                "INSERT INTO creator_claimable (anon_pubkey, mint, {claim_col}) VALUES ($1, $2, $3)
                                 ON CONFLICT (anon_pubkey, mint) DO UPDATE
                                   SET {claim_col} = creator_claimable.{claim_col} + EXCLUDED.{claim_col},
                                       updated_at = now()"
                            ),
                            &[&pk, &mint, &Num(to_creator)],
                        )
                        .await?;
                        rep.credited += 1;
                    } else {
                        rep.pool_revenue += 1;
                    }
                    pool_part
                }
                _ => {
                    rep.pool_revenue += 1;
                    amount
                }
            };
            if is_zec {
                tx.execute(
                    "UPDATE creator_fee_sweeps SET credited_at = date_trunc('hour', now()),
                            pool_quote_amount = $2::numeric
                     WHERE id = $1",
                    &[&id, &Num(pool_part)],
                )
                .await?;
            } else {
                tx.execute(
                    "UPDATE creator_fee_sweeps SET credited_at = date_trunc('hour', now()), pool_lamports = $2
                     WHERE id = $1",
                    &[&id, &Num(pool_part)],
                )
                .await?;
            }
        }
        tx.commit().await?;
        Ok(rep)
    }

    /// `Portfolio.claimable`: (mint, lamports, zat) with a positive amount (v0.14: zat of
    /// ZEC-pair fees).
    pub async fn claimable(&self, pk: &[u8; 32]) -> Result<Vec<(String, u128, u64)>> {
        let pk_s: &[u8] = pk;
        let c = self.pool.get().await?;
        Ok(c.query(
            "SELECT mint, lamports, zat FROM creator_claimable
             WHERE anon_pubkey = $1 AND (lamports > 0 OR zat > 0) ORDER BY mint",
            &[&pk_s],
        )
        .await?
        .into_iter()
        .map(|r| (r.get(0), r.get::<_, Num>(1).u128_or_zero(), to_u64(r.get(2))))
        .collect())
    }

    /// `claim {mint?}`: claimable lamports (of one mint or all) → ZEC at `rate` (lamports per
    /// ZEC, sell side). Ledger only. Below `CreatorRules::min_claim_zat` → BelowMinimum (nothing
    /// changes).
    pub async fn claim(
        &self,
        pk: &[u8; 32],
        nonce: &[u8; 16],
        request_hash: &[u8; 32],
        mint: Option<&str>,
        rate: &RateUsed,
    ) -> Result<ActionReceipt> {
        let mut c = self.pool.get().await?;
        let tx = c.transaction().await?;
        let r = self.claim_in(&tx, pk, nonce, request_hash, mint, rate).await?;
        tx.commit().await?;
        Ok(r)
    }

    /// [`Self::claim`] inside a caller's transaction (scenario `claim`).
    pub async fn claim_in<C: GenericClient>(
        &self,
        tx: &C,
        pk: &[u8; 32],
        nonce: &[u8; 16],
        request_hash: &[u8; 32],
        mint: Option<&str>,
        rate: &RateUsed,
    ) -> Result<ActionReceipt> {
        let pk_s: &[u8] = pk;
        let a = NewAction {
            kind: "claim".into(),
            rate: Some(rate.clone()),
            ..NewAction::default()
        };
        let mut receipt = self.submit_in(tx, pk, nonce, request_hash, &a).await?;
        if receipt.replayed {
            return Ok(receipt);
        }
        let rows = tx
            .query(
                "SELECT mint, lamports, zat FROM creator_claimable
                 WHERE anon_pubkey = $1 AND (lamports > 0 OR zat > 0) AND ($2::text IS NULL OR mint = $2)
                 FOR UPDATE",
                &[&pk_s, &mint],
            )
            .await?;
        let lamports: u128 = rows.iter().map(|r| r.get::<_, Num>(1).u128_or_zero()).sum();
        // v0.14: ZEC-pair fees are owed in zat already (1:1, no rate).
        let fee_zat: u64 = rows.iter().map(|r| to_u64(r.get(2))).sum();
        let zat = u64::try_from(lamports.saturating_mul(ZAT_PER_ZEC) / (rate.lamports_per_zec.max(1) as u128))
            .map_err(|_| LedgerError::Range)?;
        let zat = zat.saturating_add(fee_zat);
        if rows.is_empty() || zat < self.rules.min_claim_zat.max(1) {
            return Err(LedgerError::BelowMinimum);
        }
        for r in &rows {
            let m: String = r.get(0);
            tx.execute(
                "UPDATE creator_claimable SET claimed_lamports = claimed_lamports + lamports, lamports = 0,
                        claimed_zat = claimed_zat + zat, zat = 0, updated_at = now()
                 WHERE anon_pubkey = $1 AND mint = $2",
                &[&pk_s, &m],
            )
            .await?;
        }
        let z = to_i64(zat)?;
        tx.execute(
            "INSERT INTO balances (anon_pubkey, available_zat) VALUES ($1, $2)
             ON CONFLICT (anon_pubkey) DO UPDATE SET available_zat = balances.available_zat + EXCLUDED.available_zat,
                                                     updated_at = now()",
            &[&pk_s, &z],
        )
        .await?;
        let aid: &[u8] = &receipt.id;
        journal(tx, pk_s, "fee_credit", z, 0, None, Some(aid)).await?;
        let fill = json!({
            "solAmount": lamports.to_string(),
            "zecCredited": zat.to_string(),
            "tokenAmount": "0",
            "executedAt": crate::actions::minute_now_ms(),
        });
        tx.execute(
            "UPDATE actions SET status = 'executed', amount_zat = $2, fill = $3, updated_at = now() WHERE id = $1",
            &[&aid, &z, &fill],
        )
        .await?;
        receipt.status = "executed".into();
        Ok(receipt)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn launch_fee_fact_and_estimate() {
        let r = CreatorRules::default();
        // Exact figure from the relayer wins, clamped to what the tx paid.
        assert_eq!(
            launch_creator_fee(&r, Some("pumpfun"), 1_000_000_000, Some(500_000)),
            500_000
        );
        assert_eq!(launch_creator_fee(&r, Some("pumpfun"), 1_000, Some(5_000)), 1_000);
        assert_eq!(launch_creator_fee(&r, Some("pumpfun"), 1_000, Some(-1)), 0);
        // Estimate: 30 bps pump.fun, 40 bps DBC, rounded UP (pool side).
        assert_eq!(launch_creator_fee(&r, Some("pumpfun"), 1_000_000_000, None), 3_000_000);
        assert_eq!(
            launch_creator_fee(&r, Some("meteora-dbc"), 1_000_000_000, None),
            4_000_000
        );
        assert_eq!(launch_creator_fee(&r, None, 1, None), 1);
        assert_eq!(launch_creator_fee(&r, Some("pumpfun"), 0, None), 0);
        assert_eq!(launch_creator_fee(&r, Some("pumpfun"), -5, None), 0);
        // Huge values do not overflow.
        assert_eq!(
            launch_creator_fee(&r, Some("pumpfun"), i64::MAX as i128, None),
            ((i64::MAX as u128) * 30).div_ceil(10_000) as i128
        );
        // 18-decimal quote (wei): 4.2 ETH paid, 30 bps → 0.0126 ETH; 1e27 does not overflow.
        assert_eq!(
            launch_creator_fee(&r, Some("pons"), 4_200_000_000_000_000_000, None),
            12_600_000_000_000_000
        );
        assert_eq!(launch_creator_fee(&r, None, 10i128.pow(27), None), 3 * 10i128.pow(24));
    }
}
