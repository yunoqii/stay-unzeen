-- Unzeen 0013: launch-tx creator fee to the pool, creator cabinet, daily public stats (API.md v0.9).

-- ---------------------------------------------------------------- launch-tx creator fee (pool's)
-- Exact creator fee of a create / fair_create tx (pump.fun TradeEvent.creatorFee of the launch
-- buy; DBC: creator share of the trading fee). Written by the relayer when it knows it
-- (RELAYER v6); NULL → core uses an upper-bound estimate from out_lamports.
ALTER TABLE relayer_jobs ADD COLUMN out_creator_fee BIGINT CHECK (out_creator_fee >= 0);

-- launch_fee_lamports: creator fee generated by the launch tx itself (owner decision 12.10:
-- it belongs to the pool, it is the participants' money). launch_fee_left: part of it not yet
-- withheld from creator sweeps of this mint.
ALTER TABLE creator_tokens
    ADD COLUMN launch_fee_lamports BIGINT NOT NULL DEFAULT 0 CHECK (launch_fee_lamports >= 0),
    ADD COLUMN launch_fee_left     BIGINT NOT NULL DEFAULT 0 CHECK (launch_fee_left >= 0),
    ADD CHECK (launch_fee_left <= launch_fee_lamports);

-- Core only: part of a creator sweep kept by the pool (launch-tx fee). Not granted to the relayer.
ALTER TABLE creator_fee_sweeps ADD COLUMN pool_lamports BIGINT CHECK (pool_lamports >= 0);

-- Creator cabinet: lamports already converted by `claim` (per mint). Owner-only.
ALTER TABLE creator_claimable
    ADD COLUMN claimed_lamports BIGINT NOT NULL DEFAULT 0 CHECK (claimed_lamports >= 0);

-- ---------------------------------------------------------------- daily public stats (H6)
-- One row per network and UTC day, computed once after 00:00 UTC (devnet: manual command).
-- GET /api/stats serves the latest row only: there is no realtime aggregate anywhere.
-- zec_*: the published shielded total moves only when >= k new deposits were credited since
-- the last move (no per-deposit delta), and is rounded.
CREATE TABLE stats_snapshots (
    network        TEXT NOT NULL CHECK (network IN ('devnet', 'mainnet-beta')),
    day            DATE NOT NULL,                   -- data cut-off = 00:00 UTC of this day
    data           JSONB NOT NULL,                  -- PlatformStats without asOf
    zec_zat        BIGINT NOT NULL CHECK (zec_zat >= 0),        -- published total (rounded)
    zec_deposits   BIGINT NOT NULL CHECK (zec_deposits >= 0),   -- deposit count at that publication
    created_at     TIMESTAMPTZ NOT NULL DEFAULT date_trunc('day', now(), 'UTC'),
    PRIMARY KEY (network, day)
);
