import { existsSync, readFileSync } from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { bytesToHex, hexToBytes } from "@noble/hashes/utils.js";
import { base58 } from "@scure/base";
import { keypairFromSecret } from "./keys";
import { checkUnz1, decodeUnz1, encodeUnz1, unz1MemoString, type ChainId, type Unz1Fields, type Unz1Target } from "./unz1";
import web from "./testdata/unz1-web-vectors.json";

type Vec = (typeof web.vectors)[number] & { meta?: { name: string; symbol: string; image?: string }; mint?: string };

function fieldsOf(v: Vec): Unz1Fields {
  const t = v.target as { kind: string; receiverHex?: string; address?: string };
  const target: Unz1Target =
    t.kind === "none"
      ? { kind: "none" }
      : t.kind === "shielded"
        ? { kind: "shielded", receiver: hexToBytes(t.receiverHex!) }
        : { kind: "solana", address: t.address! };
  return {
    op: v.op as Unz1Fields["op"],
    venue: v.venue as Unz1Fields["venue"],
    mint: v.mint,
    meta: v.meta,
    minOut: BigInt(v.minOut),
    nonce: BigInt(v.nonce),
    expiry: v.expiry,
    target,
  };
}

const sk = hexToBytes(web.secretKeyHex);

describe("unz1: web vectors (generated independently with node:crypto)", () => {
  it("uses the vector key", () => {
    expect(keypairFromSecret(sk).pubkey).toBe(web.anonPubkey);
  });
  for (const v of web.vectors as Vec[]) {
    it(v.name, () => {
      const chain = v.chainId as unknown as ChainId;
      const bytes = encodeUnz1(fieldsOf(v), sk, chain);
      expect(bytesToHex(bytes)).toBe(v.memoHex);
      expect(bytes.length).toBe(v.memoLength);
      expect(unz1MemoString(fieldsOf(v), sk, chain)).toBe(v.memo);
      const d = decodeUnz1(v.memo, chain);
      expect(d.valid).toBe(true);
      expect(d.op).toBe(v.op);
      expect(d.nonce.toString()).toBe(v.nonce);
      expect(d.minOut.toString()).toBe(v.minOut);
      expect(d.anonPubkey).toBe(web.anonPubkey);
    });
  }
});

describe("unz1: rules", () => {
  const base: Unz1Fields = { op: "deposit", venue: "none", minOut: BigInt(0), nonce: BigInt(1), expiry: 1_760_003_600, target: { kind: "none" } };

  it("is 153 bytes without a target, 196 with a shielded one", () => {
    expect(encodeUnz1(base, sk, [2, 2]).length).toBe(153);
    expect(encodeUnz1({ ...base, op: "buy", venue: "pumpfun", mint: web.anonPubkey, target: { kind: "shielded", receiver: new Uint8Array(43) } }, sk, [2, 2]).length).toBe(196);
  });

  it("binds chain_id: a testnet memo does not verify on mainnet", () => {
    const m = unz1MemoString(base, sk, [2, 2]);
    expect(decodeUnz1(m, [2, 2]).valid).toBe(true);
    expect(decodeUnz1(m, [1, 1]).valid).toBe(false);
    expect(decodeUnz1(m, [2, 1]).valid).toBe(false);
  });

  it("any flipped byte breaks the signature", () => {
    const b = encodeUnz1({ ...base, op: "withdraw", venue: "pumpfun", mint: web.anonPubkey, target: { kind: "solana", address: web.anonPubkey } }, sk, [2, 2]);
    for (const off of [2, 3, 10, 40, 50, 80, 86, 100]) {
      const c = b.slice();
      c[off] ^= 1;
      let valid = false;
      try {
        valid = decodeUnz1(c, [2, 2]).valid;
      } catch {
        valid = false;
      }
      expect(valid, `offset ${off}`).toBe(false);
    }
  });

  it("rejects out-of-range and inconsistent fields", () => {
    expect(() => encodeUnz1({ ...base, nonce: BigInt(-1) }, sk, [2, 2])).toThrow();
    expect(() => encodeUnz1({ ...base, nonce: BigInt(1) << BigInt(64) }, sk, [2, 2])).toThrow();
    expect(() => encodeUnz1({ ...base, expiry: 2 ** 32 }, sk, [2, 2])).toThrow();
    expect(() => encodeUnz1({ ...base, minOut: BigInt(5) }, sk, [2, 2])).toThrow();
    expect(() => encodeUnz1({ ...base, op: "buy", venue: "pumpfun" }, sk, [2, 2])).toThrow(); // no mint
    expect(() => encodeUnz1({ ...base, op: "create", venue: "pumpfun" }, sk, [2, 2])).toThrow(); // no meta
    expect(() => encodeUnz1({ ...base, target: { kind: "shielded", receiver: new Uint8Array(42) } }, sk, [2, 2])).toThrow();
  });
});

// Backend vectors: core/testdata/unz1-vectors.json (generated by core/protocol/tests/vectors.rs).
const BACKEND = path.resolve(import.meta.dirname, "../../../core/testdata/unz1-vectors.json");

interface BackendMemoCase {
  name: string;
  expect: "valid" | "malformed" | "bad_signature" | "expired";
  secretKeyHex: string;
  anonPubkeyB58: string;
  bytesHex: string;
  memo: string;
  now: number;
  signChainIdHex: string;
  verifyChainIdHex: string;
  fields: {
    op: Unz1Fields["op"];
    venue: Unz1Fields["venue"];
    mintB58: string;
    minOut: number | string;
    nonce: number | string;
    expiry: number;
    targetKind: number;
    targetHex: string;
  };
}

const backendMemo: BackendMemoCase[] = existsSync(BACKEND)
  ? (JSON.parse(readFileSync(BACKEND, "utf8")) as { memo?: { cases?: BackendMemoCase[] } }).memo?.cases ?? []
  : [];

const chain = (hex: string) => Array.from(hexToBytes(hex)) as unknown as ChainId;

describe.skipIf(backendMemo.length === 0)("unz1: backend vectors (core/testdata/unz1-vectors.json)", () => {
  for (const c of backendMemo) {
    it(`${c.name} -> ${c.expect}`, () => {
      // Our verdict equals the backend's.
      expect(checkUnz1(c.memo, chain(c.verifyChainIdHex), c.now)).toBe(c.expect);
      expect(checkUnz1(hexToBytes(c.bytesHex), chain(c.verifyChainIdHex), c.now)).toBe(c.expect);

      // Our encoder reproduces the exact bytes for every case built from honest fields.
      if (c.name === "bad_signature") return; // bytes deliberately corrupted
      const f = c.fields;
      const target: Unz1Target =
        f.targetKind === 0
          ? { kind: "none" }
          : f.targetKind === 1
            ? { kind: "shielded", receiver: hexToBytes(f.targetHex) }
            : { kind: "solana", address: base58.encode(hexToBytes(f.targetHex)) };
      const fields: Unz1Fields = {
        op: f.op,
        venue: f.venue,
        mint: f.op === "deposit" ? undefined : f.mintB58,
        minOut: BigInt(f.minOut),
        nonce: BigInt(f.nonce),
        expiry: f.expiry,
        target,
      };
      const sk = hexToBytes(c.secretKeyHex);
      expect(keypairFromSecret(sk).pubkey).toBe(c.anonPubkeyB58);
      expect(bytesToHex(encodeUnz1(fields, sk, chain(c.signChainIdHex)))).toBe(c.bytesHex);
      expect(unz1MemoString(fields, sk, chain(c.signChainIdHex))).toBe(c.memo);
    });
  }
});
